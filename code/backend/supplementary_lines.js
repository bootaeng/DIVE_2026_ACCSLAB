// Common empty-facility fields so downstream code sees consistent shapes.
function decorate(list, lineName) {
  return list.map(s => ({
    id: s.id,
    name: s.name,
    line: lineName,
    lat: s.lat,
    lng: s.lng,
    address: '',
    tel: '',
    transferType: s.transferType || '일반역',
    transferLines: '',
    elevators: [],
    escalators: [],
    gaps: [],
    lockers: [],
    atms: [],
    chargers: [],
    kiosks: [],
    supplementary: true
  }))
}

